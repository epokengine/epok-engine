//! Small bitmap fonts drawn on the 32x32 screen.

/// 3x5 glyphs for ASCII 32..=95; lowercase letters use the uppercase glyphs.
/// Each glyph is five rows of three pixels, bit 0 = left.
pub const SMALL: [[u8; 5]; 64] = {
    const fn g(rows: [&str; 5]) -> [u8; 5] {
        let mut out = [0u8; 5];
        let mut r = 0;
        while r < 5 {
            let bytes = rows[r].as_bytes();
            let mut c = 0;
            while c < 3 {
                if bytes[c] == b'#' {
                    out[r] |= 1 << c;
                }
                c += 1;
            }
            r += 1;
        }
        out
    }
    [
        g(["...", "...", "...", "...", "..."]), // space
        g([".#.", ".#.", ".#.", "...", ".#."]), // !
        g(["#.#", "#.#", "...", "...", "..."]), // "
        g(["#.#", "###", "#.#", "###", "#.#"]), // #
        g([".##", "##.", ".#.", ".##", "##."]), // $
        g(["#.#", "..#", ".#.", "#..", "#.#"]), // %
        g([".#.", "#.#", ".#.", "#.#", ".##"]), // &
        g([".#.", ".#.", "...", "...", "..."]), // '
        g(["..#", ".#.", ".#.", ".#.", "..#"]), // (
        g(["#..", ".#.", ".#.", ".#.", "#.."]), // )
        g(["...", "#.#", ".#.", "#.#", "..."]), // *
        g(["...", ".#.", "###", ".#.", "..."]), // +
        g(["...", "...", "...", ".#.", "#.."]), // ,
        g(["...", "...", "###", "...", "..."]), // -
        g(["...", "...", "...", "...", ".#."]), // .
        g(["..#", "..#", ".#.", "#..", "#.."]), // /
        g(["###", "#.#", "#.#", "#.#", "###"]), // 0
        g([".#.", "##.", ".#.", ".#.", "###"]), // 1
        g(["###", "..#", "###", "#..", "###"]), // 2
        g(["###", "..#", ".##", "..#", "###"]), // 3
        g(["#.#", "#.#", "###", "..#", "..#"]), // 4
        g(["###", "#..", "###", "..#", "###"]), // 5
        g(["###", "#..", "###", "#.#", "###"]), // 6
        g(["###", "..#", ".#.", ".#.", ".#."]), // 7
        g(["###", "#.#", "###", "#.#", "###"]), // 8
        g(["###", "#.#", "###", "..#", "###"]), // 9
        g(["...", ".#.", "...", ".#.", "..."]), // :
        g(["...", ".#.", "...", ".#.", "#.."]), // ;
        g(["..#", ".#.", "#..", ".#.", "..#"]), // <
        g(["...", "###", "...", "###", "..."]), // =
        g(["#..", ".#.", "..#", ".#.", "#.."]), // >
        g(["###", "..#", ".#.", "...", ".#."]), // ?
        g([".#.", "#.#", "###", "#..", ".##"]), // @
        g([".#.", "#.#", "###", "#.#", "#.#"]), // A
        g(["##.", "#.#", "##.", "#.#", "##."]), // B
        g([".##", "#..", "#..", "#..", ".##"]), // C
        g(["##.", "#.#", "#.#", "#.#", "##."]), // D
        g(["###", "#..", "##.", "#..", "###"]), // E
        g(["###", "#..", "##.", "#..", "#.."]), // F
        g([".##", "#..", "#.#", "#.#", ".##"]), // G
        g(["#.#", "#.#", "###", "#.#", "#.#"]), // H
        g(["###", ".#.", ".#.", ".#.", "###"]), // I
        g(["..#", "..#", "..#", "#.#", ".#."]), // J
        g(["#.#", "#.#", "##.", "#.#", "#.#"]), // K
        g(["#..", "#..", "#..", "#..", "###"]), // L
        g(["#.#", "###", "###", "#.#", "#.#"]), // M
        g(["##.", "#.#", "#.#", "#.#", "#.#"]), // N
        g([".#.", "#.#", "#.#", "#.#", ".#."]), // O
        g(["##.", "#.#", "##.", "#..", "#.."]), // P
        g([".#.", "#.#", "#.#", "##.", ".##"]), // Q
        g(["##.", "#.#", "##.", "#.#", "#.#"]), // R
        g([".##", "#..", ".#.", "..#", "##."]), // S
        g(["###", ".#.", ".#.", ".#.", ".#."]), // T
        g(["#.#", "#.#", "#.#", "#.#", "###"]), // U
        g(["#.#", "#.#", "#.#", "#.#", ".#."]), // V
        g(["#.#", "#.#", "###", "###", "#.#"]), // W
        g(["#.#", "#.#", ".#.", "#.#", "#.#"]), // X
        g(["#.#", "#.#", ".#.", ".#.", ".#."]), // Y
        g(["###", "..#", ".#.", "#..", "###"]), // Z
        g([".##", ".#.", ".#.", ".#.", ".##"]), // [
        g(["#..", "#..", ".#.", "..#", "..#"]), // backslash
        g(["##.", ".#.", ".#.", ".#.", "##."]), // ]
        g([".#.", "#.#", "...", "...", "..."]), // ^
        g(["...", "...", "...", "...", "###"]), // _
    ]
};

/// Glyph rows for a character (unknown characters draw as `?`).
pub fn small(c: char) -> [u8; 5] {
    let c = c.to_ascii_uppercase();
    let code = c as u32;
    if (32..96).contains(&code) {
        SMALL[(code - 32) as usize]
    } else {
        SMALL[('?' as u32 - 32) as usize]
    }
}

/// 5x7 digits for the clock.
pub const DIGITS: [[u8; 7]; 10] = {
    const fn g(rows: [&str; 7]) -> [u8; 7] {
        let mut out = [0u8; 7];
        let mut r = 0;
        while r < 7 {
            let bytes = rows[r].as_bytes();
            let mut c = 0;
            while c < 5 {
                if bytes[c] == b'#' {
                    out[r] |= 1 << c;
                }
                c += 1;
            }
            r += 1;
        }
        out
    }
    [
        g([
            ".###.", "#...#", "#..##", "#.#.#", "##..#", "#...#", ".###.",
        ]),
        g([
            "..#..", ".##..", "..#..", "..#..", "..#..", "..#..", ".###.",
        ]),
        g([
            ".###.", "#...#", "....#", "...#.", "..#..", ".#...", "#####",
        ]),
        g([
            ".###.", "#...#", "....#", "..##.", "....#", "#...#", ".###.",
        ]),
        g([
            "...#.", "..##.", ".#.#.", "#..#.", "#####", "...#.", "...#.",
        ]),
        g([
            "#####", "#....", "####.", "....#", "....#", "#...#", ".###.",
        ]),
        g([
            "..##.", ".#...", "#....", "####.", "#...#", "#...#", ".###.",
        ]),
        g([
            "#####", "....#", "...#.", "..#..", ".#...", ".#...", ".#...",
        ]),
        g([
            ".###.", "#...#", "#...#", ".###.", "#...#", "#...#", ".###.",
        ]),
        g([
            ".###.", "#...#", "#...#", ".####", "....#", "...#.", ".##..",
        ]),
    ]
};

/// A 32x32 monochrome canvas (row words, bit 0 = left, 1 = black).
#[derive(Clone, Copy, Debug, Default, PartialEq, Eq)]
pub struct Canvas(pub [u32; 32]);

impl Canvas {
    pub fn clear(&mut self) {
        self.0 = [0; 32];
    }
    pub fn set(&mut self, x: i32, y: i32, on: bool) {
        if (0..32).contains(&x) && (0..32).contains(&y) {
            if on {
                self.0[y as usize] |= 1 << x;
            } else {
                self.0[y as usize] &= !(1 << x);
            }
        }
    }
    pub fn text(&mut self, text: &str, x: i32, y: i32) {
        let mut cx = x;
        for c in text.chars() {
            let glyph = small(c);
            for (row, bits) in glyph.iter().enumerate() {
                for col in 0..3 {
                    if bits & (1 << col) != 0 {
                        self.set(cx + col, y + row as i32, true);
                    }
                }
            }
            cx += 4;
        }
    }
    pub fn digit(&mut self, d: u32, x: i32, y: i32) {
        let glyph = DIGITS[(d % 10) as usize];
        for (row, bits) in glyph.iter().enumerate() {
            for col in 0..5 {
                if bits & (1 << col) != 0 {
                    self.set(x + col, y + row as i32, true);
                }
            }
        }
    }
    pub fn rect(&mut self, x: i32, y: i32, w: i32, h: i32) {
        for yy in y..y + h {
            for xx in x..x + w {
                self.set(xx, yy, true);
            }
        }
    }
    pub fn image(&mut self, image: &[u32; 32]) {
        self.0 = *image;
    }
}
